// Package permsmatrix renders the reviewable permissions matrix (moxy#496):
// one row per moxin tool, built from the same parse the server uses
// (internal/native), so the table cannot describe a tool differently from how
// it is served.
//
// Everything in a Row except PathInputs is read straight from the tool's TOML
// (verified). PathInputs is an inference from input names and is labelled as
// such wherever it is rendered.
package permsmatrix

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"code.linenisgreat.com/moxy/internal/native"
)

// Row is one tool's permission facts.
type Row struct {
	Server, Tool string

	// Tier is the tool's perms-request, with the default spelled out.
	Tier native.PermsRequest
	// Floor is the [dynamic-perms] command (base name) and its fixed args.
	Floor string
	// Resources are the tool's [resources.*] stanzas as "input:op[+split|+grammar]".
	Resources []string
	// Async is whether the tool may be backgrounded (permit-async).
	Async bool
	// Hints are the tool's declared annotations, as "key=value".
	Hints []string
	// PathInputs are inputs whose name suggests a path, directory, repo or
	// session id. Inferred from names, not from behaviour.
	PathInputs []string
}

// pathInput matches input names that usually carry something to open.
var pathInput = regexp.MustCompile(`^(name|page)$|(^|[-_])(path|paths|file|files|dir|dirs|cwd|folder|root|source|destination|target|installable|flake_dir|repo_path|session_id|session_ids)$`)

// Build returns the rows for every tool of every config, sorted by
// server then tool.
func Build(configs []*native.NativeConfig) []Row {
	var rows []Row
	for _, cfg := range configs {
		for i := range cfg.Tools {
			rows = append(rows, rowOf(cfg.Name, &cfg.Tools[i]))
		}
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Server != rows[j].Server {
			return rows[i].Server < rows[j].Server
		}
		return rows[i].Tool < rows[j].Tool
	})
	return rows
}

func rowOf(server string, t *native.ToolSpec) Row {
	r := Row{Server: server, Tool: t.Name, Tier: t.PermsRequest, Async: t.PermitsAsync()}
	if r.Tier == "" {
		r.Tier = native.PermsDelegateToClient
	}
	if d := t.DynamicPerms; d != nil {
		r.Floor = strings.TrimSpace(filepath.Base(d.Command) + " " + strings.Join(d.Args, " "))
	}
	for _, res := range t.Resources {
		s := res.Param + ":" + res.Op
		switch {
		case res.Split:
			s += "+split"
		case res.Grammar != "":
			s += "+" + res.Grammar
		}
		r.Resources = append(r.Resources, s)
	}
	if a := t.Annotations; a != nil {
		for _, h := range []struct {
			key string
			v   *bool
		}{
			{"read-only", a.ReadOnlyHint},
			{"destructive", a.DestructiveHint},
			{"idempotent", a.IdempotentHint},
			{"open-world", a.OpenWorldHint},
		} {
			if h.v != nil {
				r.Hints = append(r.Hints, fmt.Sprintf("%s=%t", h.key, *h.v))
			}
		}
	}
	if t.InputParsed != nil {
		for name := range t.InputParsed.Properties {
			if pathInput.MatchString(name) {
				r.PathInputs = append(r.PathInputs, name)
			}
		}
		sort.Strings(r.PathInputs)
	}
	return r
}

// ResourceGated reports whether the policy broker is asked about any of the
// tool's inputs (it is asked per [resources.*] input and nowhere else).
func (r Row) ResourceGated() bool {
	return r.Tier == native.PermsDynamic && len(r.Resources) > 0
}

// UngatedPathReader reports whether a tool takes an input that looks like a
// path or id, is always allowed, and names no resources: nothing — neither
// the broker nor a floor — looks at what that input points at. The "looks
// like" half is inferred (see Row.PathInputs).
func (r Row) UngatedPathReader() bool {
	return r.Tier == native.PermsAlwaysAllow && len(r.Resources) == 0 && len(r.PathInputs) > 0
}

// Gate is the one-word summary of who judges the tool's inputs.
func (r Row) Gate() string {
	switch {
	case r.ResourceGated():
		return "broker+floor"
	case r.Tier == native.PermsDynamic:
		return "floor"
	case r.Tier == native.PermsAlwaysAllow:
		return "none"
	case r.Tier == native.PermsEachUse:
		return "prompt"
	default:
		return "client"
	}
}

// Render writes the matrix as markdown. The output is deterministic.
func Render(rows []Row) string {
	var b strings.Builder
	b.WriteString("<!-- generated by `moxy perms-matrix`; do not edit (just debug-perms-matrix) -->\n\n")
	b.WriteString("# Moxin tool permissions matrix\n\n")
	b.WriteString("Verified columns come from the parsed tool TOML. `path inputs` is inferred from input names.\n\n")

	counts := map[native.PermsRequest]int{}
	var flagged []Row
	for _, r := range rows {
		counts[r.Tier]++
		if r.UngatedPathReader() {
			flagged = append(flagged, r)
		}
	}
	fmt.Fprintf(&b, "%d tools: %d always-allow, %d dynamic, %d each-use, %d delegate-to-client.\n\n",
		len(rows), counts[native.PermsAlwaysAllow], counts[native.PermsDynamic],
		counts[native.PermsEachUse], counts[native.PermsDelegateToClient])

	b.WriteString("## Matrix\n\n")
	b.WriteString("| tool | tier | gate | floor | resources | async | hints | path inputs (inferred) |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s.%s` | %s | %s | %s | %s | %t | %s | %s |\n",
			r.Server, r.Tool, r.Tier, r.Gate(), cell(r.Floor), cell(strings.Join(r.Resources, ", ")),
			r.Async, cell(strings.Join(r.Hints, ", ")), cell(strings.Join(r.PathInputs, ", ")))
	}

	b.WriteString("\n## Ungated path readers (inferred)\n\n")
	b.WriteString("always-allow, no `[resources]` stanza, and an input whose name looks like a path or id.\n\n")
	if len(flagged) == 0 {
		b.WriteString("none\n")
	}
	for _, r := range flagged {
		fmt.Fprintf(&b, "- `%s.%s`: %s\n", r.Server, r.Tool, strings.Join(r.PathInputs, ", "))
	}
	return b.String()
}

func cell(s string) string {
	if s == "" {
		return "–"
	}
	return "`" + s + "`"
}
